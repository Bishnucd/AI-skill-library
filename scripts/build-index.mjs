#!/usr/bin/env node
/**
 * Community List – regenerate SKILLS_INDEX.md from SKILL.md frontmatter.
 *
 *   node scripts/build-index.mjs           write SKILLS_INDEX.md
 *   node scripts/build-index.mjs --check   exit 1 if the file is out of date
 *
 * The generated block sits between the two markers so hand-written prose above and
 * below the markers is preserved.
 */

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, "..");
const SKILLS = path.join(ROOT, "skills");
const INDEX = path.join(ROOT, "SKILLS_INDEX.md");
const START = "<!-- BEGIN GENERATED SKILL TABLE -->";
const END = "<!-- END GENERATED SKILL TABLE -->";

const TITLES = {
  "website-development": "Website Development",
  "app-development": "App Development",
  "software-engineering": "Software Engineering",
  "agent-technologies": "Agent Technologies",
  "automation-workflows": "Automation & Workflows",
  "data-analytics": "Data & Analytics",
  "database-technologies": "Database Technologies",
  "maps-and-location": "Maps & Location",
  "image-creation": "Image Creation",
  "video-multimedia": "Video & Multimedia",
  "audio-speech": "Audio & Speech",
  "search-research": "Search & Research",
  "communication-integrations": "Communication & Integrations",
  "security-testing": "Security & Testing",
  "business-productivity": "Business & Productivity",
};

const read = (p) => fs.readFileSync(p, "utf8").replace(/\r\n/g, "\n");
const listDirs = (p) =>
  fs.existsSync(p)
    ? fs.readdirSync(p, { withFileTypes: true }).filter((d) => d.isDirectory()).map((d) => d.name).sort()
    : [];

function frontmatter(text) {
  if (!text.startsWith("---")) return {};
  const close = text.indexOf("\n---", 3);
  if (close === -1) return {};
  const data = {};
  let map = null;
  for (const line of text.slice(4, close).split("\n")) {
    const m = line.match(/^\s*([A-Za-z0-9_.-]+):\s*(.*)$/);
    if (!m) continue;
    const [, key, v] = m;
    const value = v.trim().replace(/^["'](.*)["']$/, "$1");
    if (/^\s/.test(line) && map) data[map][key] = value;
    else if (value === "") (map = key), (data[key] = {});
    else (map = null), (data[key] = value);
  }
  return data;
}

const esc = (s) => String(s ?? "").replace(/\|/g, "\\|").replace(/\n/g, " ");
const short = (s, n = 110) => (s.length > n ? s.slice(0, n - 1).trimEnd() + "…" : s);

const rows = [];
const skills = [];

for (const category of listDirs(SKILLS)) {
  for (const sub of listDirs(path.join(SKILLS, category))) {
    for (const name of listDirs(path.join(SKILLS, category, sub))) {
      const dir = path.join(SKILLS, category, sub, name);
      const skillFile = path.join(dir, "SKILL.md");
      if (!fs.existsSync(skillFile)) continue;
      const fm = frontmatter(read(skillFile));
      const rel = `skills/${category}/${sub}/${name}`;
      skills.push({ category, sub, name, rel, fm });
    }
  }
}

const count = skills.length;
let out = `${START}\n`;
out += `<!-- Generated by scripts/build-index.mjs on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand. -->\n\n`;
out += `**Total skills:** ${count} across ${new Set(skills.map((s) => s.category)).size} categories\n\n`;

for (const category of listDirs(SKILLS)) {
  const inCat = skills.filter((s) => s.category === category);
  if (!inCat.length) continue;
  out += `### ${TITLES[category] ?? category} \`${category}\`\n\n`;
  out += `| Skill | What it does | Subcategory | Licence | Path |\n`;
  out += `|-------|--------------|-------------|---------|------|\n`;
  for (const s of inCat.sort((a, b) => a.name.localeCompare(b.name))) {
    out += `| [${esc(s.name)}](${s.rel}/SKILL.md) | ${esc(short(s.fm.description ?? ""))} | \`${esc(s.sub)}\` | ${esc(s.fm.license ?? "see README")} | \`${s.rel}\` |\n`;
  }
  out += `\n`;
}
out += END;

if (!fs.existsSync(INDEX)) {
  console.error("SKILLS_INDEX.md not found; create it with the marker comments first.");
  process.exit(1);
}

const current = read(INDEX);
const startAt = current.indexOf(START);
const endAt = current.indexOf(END);
if (startAt === -1 || endAt === -1) {
  console.error(`SKILLS_INDEX.md must contain ${START} and ${END}.`);
  process.exit(1);
}

const next = current.slice(0, startAt) + out + current.slice(endAt + END.length);

if (process.argv.includes("--check")) {
  if (current !== next) {
    console.error("SKILLS_INDEX.md is out of date. Run: node scripts/build-index.mjs");
    process.exit(1);
  }
  console.log("SKILLS_INDEX.md is up to date.");
  process.exit(0);
}

fs.writeFileSync(INDEX, next, "utf8");
console.log(`Wrote SKILLS_INDEX.md with ${count} skills.`);
